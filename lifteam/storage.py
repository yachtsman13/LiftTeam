"""
Хранилище статики для рабочей установки.
v2.125.1
"""
import logging

from django.contrib.staticfiles.storage import ManifestStaticFilesStorage

logger = logging.getLogger(__name__)

# Имена, о которых уже сказано в журнал. Без этого несобранный скрипт
# из `base.html` писал бы строку на каждый показ каждой страницы.
_reported = set()


class ForgivingManifestStaticFilesStorage(ManifestStaticFilesStorage):
    """`ManifestStaticFilesStorage`, который не закрывает программу целиком.

    Готовое хранилище с манифестом, не найдя имени в `staticfiles.json`,
    бросает `ValueError` — и бросает его **из шаблона**, то есть «500»
    на каждой странице, где стоит `{% static %}`. В `base.html` таких
    ссылок два десятка, а на странице входа — ровно одна (логотип),
    и у неё свой шаблон. Поэтому промах сборки статики выглядит так:
    вход открывается, а дальше вся программа отвечает ошибкой сервера.
    Достаточно одного раза: обновились `git pull`'ом без `collectstatic`,
    кончилось место на карте посреди сборки, новая версия добавила файл.

    Это тот же случай, от которого защищаются везде в программе: полоса
    обрыва связи нарисована своими правилами, потому что Bootstrap
    приходит из интернета, а окна сетки кассетниц обёрнуты в `try`,
    потому что без него падал весь обработчик. Несобранный скрипт —
    такая же мелочь, и платой за него не может быть неоткрывающаяся
    программа.

    Делается это в два слоя, и одного `manifest_strict = False` мало:
    он только разрешает **посчитать** хэш на месте, а считается он
    чтением файла из `STATIC_ROOT`, и у файла, который туда ещё
    не собирали, не выходит и это — `ValueError` повторяется уже
    из `hashed_name`. Поэтому `stored_name` ловит отказ и отдаёт имя
    как есть, без хэша: в худшем случае браузер получит 404 на одну
    картинку или скрипт (страница работает, просто без него), в лучшем —
    nginx отдаст файл по неизменному имени.

    Молча это не проходит: о каждом таком имени один раз пишется
    в журнал (`logs/errors.log` на рабочей установке), иначе наполовину
    собранная статика живёт месяцами и выясняется случайно.

    Сборку статики всё это не отменяет и не заменяет: `collectstatic`
    как делали `deploy/update.sh` и `lifteam-update-runner.sh`, так
    и делают, — меняется только цена промаха.
    """

    manifest_strict = False

    def stored_name(self, name):
        try:
            return super().stored_name(name)
        except ValueError:
            if name not in _reported:
                _reported.add(name)
                logger.warning(
                    'Статика не собрана: %s нет ни в манифесте, ни в STATIC_ROOT. '
                    'Страница отдана без него; выполните collectstatic.', name
                )
            return name

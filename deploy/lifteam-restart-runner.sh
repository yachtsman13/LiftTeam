#!/bin/bash
# Перезапускает LiftTeam по заявке из веб-интерфейса.
#
# УСТАНАВЛИВАЕТСЯ В /usr/local/sbin/lifteam-restart, ВЛАДЕЛЕЦ root, ПРАВА 755.
#
# Класть этот файл в /opt/lifteam нельзя. Каталог приложения принадлежит
# пользователю lifteam, от которого работает веб-приложение. Если бы служба
# root запускала скрипт оттуда, то любой, кто получил доступ к приложению,
# подменил бы содержимое скрипта и выполнил произвольные команды от root.
#
# Из заявки НИЧЕГО НЕ ЧИТАЕТСЯ. У обновления в файле лежит номер версии,
# и скрипт обязан его проверять; здесь нужен один факт — файл появился.
# Поэтому подставить в этот скрипт нечего в принципе, и проверять тут
# тоже нечего.

set -uo pipefail

REQUEST_FILE="/opt/lifteam/.restart-request"
SERVICE="lifteam"

[[ -f "$REQUEST_FILE" ]] || exit 0

# Заявку убираем первой, до перезапуска: перезапуск обрывает всё, включая
# эту команду, и оставленный файл заставил бы службу сработать снова —
# приложение ушло бы в бесконечный перезапуск.
rm -f "$REQUEST_FILE"

echo "Перезапуск ${SERVICE} по заявке из интерфейса"
systemctl restart "$SERVICE"

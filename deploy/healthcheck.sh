#!/bin/bash
# Проверка, что приложение отвечает, и перезапуск, если нет.
#
# Зачем это нужно, если в службе уже стоит Restart=on-failure: тот перезапуск
# срабатывает, только когда процесс завершился. Зависший процесс продолжает
# висеть в памяти и принимать соединения, ничего не отдавая, — для systemd
# он полностью исправен, и служба остаётся «работающей», пока сотрудники
# видят ошибку.
#
# Установка описана в DEPLOY.md.

set -uo pipefail

URL="http://127.0.0.1:8000/login/"
SERVICE="lifteam"
ATTEMPTS=3
TIMEOUT=10
PAUSE=5

check() {
    # Ждём любой ответ приложения. Даже 500 означает, что процесс жив
    # и обрабатывает запросы, — перезапуск в этом случае не поможет,
    # причину надо искать в логах. Реагируем только на полное молчание.
    curl -s -o /dev/null --max-time "$TIMEOUT" "$URL"
}

for attempt in $(seq 1 "$ATTEMPTS"); do
    if check; then
        exit 0
    fi
    [[ $attempt -lt $ATTEMPTS ]] && sleep "$PAUSE"
done

echo "Приложение не ответило на ${ATTEMPTS} запроса подряд, перезапуск ${SERVICE}"

# Состояние службы до перезапуска пригодится при разборе
systemctl status "$SERVICE" --no-pager --lines=20 || true

systemctl restart "$SERVICE"
sleep 10

if check; then
    echo "Перезапуск помог, приложение отвечает"
else
    echo "После перезапуска приложение по-прежнему не отвечает — нужна проверка вручную" >&2
    exit 1
fi

"""Сетевые ошибки, названные так, чтобы по ним можно было починить.

Причина из `URLError` — это текст исключения OpenSSL или сокета: он верен,
но человеку, который читает очередь оповещений, ничего не говорит. Здесь
к таким причинам дописывается объяснение и то, что с ними делать.
"""

# Российские сервисы (MAX, Т-Банк) подписаны сертификатом НУЦ Минцифры,
# а его нет ни в одном стандартном наборе корневых сертификатов. Без него
# проверка сертификата сервера падает, и выглядит это как «сервис
# недоступен», хотя сеть в порядке и токен верный. Ровно на это мы
# потратили вечер на рабочей установке.
CERTIFICATE_HINT = (
    'в системе нет корневого сертификата НУЦ Минцифры, которым подписаны '
    'российские сервисы. Как поставить — в DEPLOY.md, раздел «Российский '
    'корневой сертификат»'
)


def explain(reason):
    """Причина сетевой ошибки с подсказкой, если она известна."""
    text = str(reason)
    if 'CERTIFICATE_VERIFY_FAILED' in text:
        return f'{text}. Похоже, {CERTIFICATE_HINT}'
    return text


# Секреты в журнале. Токен банка, попавший в лог, живёт там до ротации
# и уезжает в резервную копию — то есть перестаёт быть секретом. Поэтому
# всё, что уходит в журнал, проходит через redact: он вырезает известные
# значения токенов и заголовок Authorization целиком.
REDACTED = '***'

# Заголовки, значение которых не пишется в журнал никогда — даже если
# конкретного токена нет в списке известных
SECRET_HEADERS = ('authorization', 'x-api-key', 'cookie', 'set-cookie')


def redact(text, *secrets):
    """Текст для журнала: известные секреты заменены на «***».

    Короткие и пустые значения пропускаются намеренно: замена строки
    из двух символов испортила бы сообщение, ничего не скрыв.
    """
    result = str(text)
    for secret in secrets:
        secret = str(secret or '')
        if len(secret) < 8:
            continue
        result = result.replace(secret, REDACTED)
    return result


def safe_headers(headers):
    """Заголовки для журнала: значения секретных заменены на «***»."""
    return {
        name: (REDACTED if str(name).lower() in SECRET_HEADERS else value)
        for name, value in dict(headers).items()
    }

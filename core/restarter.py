"""
Перезапуск службы по заявке из интерфейса.

Приложение работает от пользователя `lifteam` и перезапустить себя
не может: для этого нужен root, а давать веб-приложению sudo нельзя —
тогда любая уязвимость в нём означала бы root на устройстве.

Приём тот же, что у обновления (`core/updater.py`): приложение создаёт
файл-заявку, а привилегированную работу выполняет служба systemd,
следящая за появлением этого файла. Скрипт, который она запускает, лежит
вне каталога приложения и принадлежит root — лежи он рядом с кодом,
взломщик подменил бы его и получил выполнение от root.

Отличие от обновления в том, что **из заявки ничего не читается**.
У обновления в файле лежит версия, и скрипт обязан её проверять; здесь
скрипту нужен один факт — файл появился. Поэтому подставить в него
нечего в принципе.

Зачем это понадобилось. Почти все настройки подхватываются на ходу
(`core/envfile.py`), но не все: `ALLOWED_HOSTS`, `CSRF_TRUSTED_ORIGINS`,
часовой пояс и пароль почты Django читает один раз при запуске. Пока
кнопки не было, такие настройки не имело смысла и показывать —
поправленные, они молча не действовали.
"""
import json
from pathlib import Path

from django.conf import settings
from django.utils import timezone

APP_DIR = Path(settings.BASE_DIR)
REQUEST_FILE = APP_DIR / '.restart-request'

# Куда установлен привилегированный скрипт. Проверяем именно его, а не
# юнит systemd: без скрипта заявка легла бы в каталог и осталась там
# навсегда, а страница обещала бы перезапуск, которого не будет
RUNNER = Path('/usr/local/sbin/lifteam-restart')


def is_available():
    """Настроен ли перезапуск из интерфейса.

    На машине разработчика его нет и быть не должно — там служба
    запускается руками.
    """
    return RUNNER.exists()


def pending():
    """Заявка подана и ещё не подхвачена службой.

    Файл удаляет сам привилегированный скрипт, первым же действием.
    Поэтому исчезновение файла означает «служба взялась за дело»,
    а не «перезапуск закончился».
    """
    return REQUEST_FILE.exists()


def request_restart(requested_by=''):
    """Оставить заявку. Саму работу выполнит служба от root.

    Содержимое файла нужно только для разбора неполадок: служба его
    не читает и читать не должна.
    """
    REQUEST_FILE.write_text(
        json.dumps(
            {
                'requested_by': requested_by,
                'requested_at': timezone.now().isoformat(timespec='seconds'),
            },
            ensure_ascii=False,
        ),
        encoding='utf-8',
    )


def cancel():
    """Убрать неподхваченную заявку.

    Нужно ровно для одного случая: перезапуск из интерфейса не настроен,
    заявка легла и лежит. Ждать её вечно и показывать «служба вот-вот
    перезапустится» — врать.
    """
    try:
        REQUEST_FILE.unlink()
    except FileNotFoundError:
        pass

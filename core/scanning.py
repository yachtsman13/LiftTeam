"""
Разбор того, что пришло со сканера штрихкодов.

Сканер — это клавиатура: он «набирает» содержимое кода и жмёт Enter.
В коде на этикетке лежит ссылка вида `http://lifteam.taile9b605.ts.net/p/12`
(её собирает `views.qr_url`), поэтому со сканера приходит целая ссылка,
а не номер записи.

С v2.61.0 в новые наклейки кладётся короткое содержимое без адреса
сервера — `u/123`. Прежнее, со ссылкой целиком, читается по-прежнему:
наклейки, наклеенные раньше, переклеивать по всему складу некому.

Узнаём код **по виду пути, а не по адресу сервера**. Этикетки печатаются
с той основы, что задана в `LABEL_BASE_URL`, и на наклейке она впечатана
навсегда: на старой может стоять локальный адрес, на новой — имя
в Tailscale. Требовать совпадения с адресом, откуда открыта страница,
значило бы, что вчерашняя наклейка сегодня не читается, — а переклеивать
их по всему складу некому. Зато вид пути (`/p/<номер>`) свой и ни с чем
не совпадает.

Снисходительны к тому, что пришло, и строги к тому, что из этого следует:
принимаем ссылку целиком, голый путь, лишние пробелы и невидимые символы,
хвост запроса — но если после этого путь не один из четырёх, ответ один:
«это не наш код». Догадываться нельзя: неверно угаданный номер откроет
чужую карточку, а человек со сканером в руках этого не заметит.
"""
import re

# Приставки коротких адресов (`core/urls.py`) и то, что они означают.
# Буква `e` осталась, хотя отдельную этикетку оборудования больше
# не печатают: наклеенные раньше коды должны читаться и дальше.
KINDS = {
    'p': 'part',
    'c': 'cell',
    'e': 'equipment',
    'o': 'order',
    # Единица оборудования в конкретном заказе. Это и есть то, что наклеено
    # на приборе: мастеру с платой в руках нужна не «эта железка вообще»
    # и не «весь заказ», а «эта железка в этой работе».
    'u': 'order_equipment',
}

KIND_LABELS = {
    'part': 'Радиодеталь',
    'cell': 'Ячейка хранения',
    'equipment': 'Оборудование',
    'order': 'Заказ на ремонт',
    'order_equipment': 'Оборудование в заказе',
}

# Путь целиком: одна буква, номер, необязательная косая черта на конце.
# В QR-коды уходит вариант без черты (так короче на символ), но код могли
# и перенабрать руками из строки браузера — там она есть.
_PATH = re.compile(r'^/?(?P<kind>[pceouPCEOU])/(?P<pk>\d+)/?$')

# Начало ссылки: схема и адрес сервера. Отбрасывается целиком — адрес
# на наклейке к делу не относится.
_ORIGIN = re.compile(r'^[a-z][a-z0-9+.\-]*://[^/]*', re.IGNORECASE)

# Невидимое, что приезжает вместе с содержимым кода: неразрывный пробел,
# метка порядка байтов, нулевой байт. Сканеры добавляют такое сами,
# а на глаз строка выглядит обычной.
_INVISIBLE = ' \u00a0\u200b\u200e\u200f\ufeff\x00'


def decode(payload):
    """Разобрать содержимое кода в `{'kind': ..., 'id': ...}` или `None`.

    `None` означает ровно одно: это не код LiftTeam. Ни вид, ни номер
    из такого кода не выдумываются.
    """
    if not payload:
        return None

    text = str(payload).strip().strip(_INVISIBLE).strip()
    if not text:
        return None

    # Адрес сервера отбрасываем: на наклейке он может быть любым
    text = _ORIGIN.sub('', text, count=1)
    # Хвост запроса и якорь к виду пути отношения не имеют
    text = text.split('?', 1)[0].split('#', 1)[0].strip()

    match = _PATH.match(text)
    if not match:
        return None

    return {
        'kind': KINDS[match.group('kind').lower()],
        'id': int(match.group('pk')),
    }


def kind_label(kind):
    """Название вида по-русски — для сообщений человеку."""
    return KIND_LABELS.get(kind, 'Неизвестный вид')
